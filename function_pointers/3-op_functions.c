#include "3-calc.h"

/**
 * op_add - addition
 * @a: nombre 1
 * @b: nombre 2
 * Return: a+b
 */
int op_add(int a, int b)
{
	return (a + b);
}

/**
 * op_sub - soustraction
 * @a: nombre 1
 * @b: nombre 2
 * Return: a-b
 */
int op_sub(int a, int b)
{
	return (a - b);
}

/**
 * op_mul - multiplication
 * @a: nombre 1
 * @b: nombre 2
 * Return: a*b
 */
int op_mul(int a, int b)
{
	return (a * b);
}

/**
 * op_div - division
 * @a: nombre 1
 * @b: nombre 2
 * Return: a/b
 */
int op_div(int a, int b)
{
	return (a / b);
}

/**
 * op_mod - reste de la division
 * @a: nombre 1
 * @b: nombre 2
 * Return: a%b
 */
int op_mod(int a, int b)
{
	return (a % b);
}
